// Writes THIRD-PARTY-NOTICES.md from package-lock.json: every package the app ships (not dev-only).
// Usage: node scripts/third-party-notices.mjs            (rewrite the file)
//        node scripts/third-party-notices.mjs --check    (exit 1 when the file is out of date)
import { readFileSync, writeFileSync } from "node:fs";

const lock = JSON.parse(readFileSync("package-lock.json", "utf8"));
const manifest = JSON.parse(readFileSync("package.json", "utf8"));

// Packages the renderer bundle includes although they are development dependencies (the bundler
// copies their code into the app), plus everything they need at run time.
const bundled = new Set();
const visit = (name) => {
  const key = `node_modules/${name}`;
  const info = lock.packages[key];
  if (!info || bundled.has(key)) return;
  bundled.add(key);
  for (const dep of Object.keys({ ...info.dependencies, ...info.optionalDependencies })) visit(dep);
};
for (const name of manifest.sheetstamp?.bundledDevDependencies ?? []) visit(name);

const rows = [];
const missing = [];
for (const [path, info] of Object.entries(lock.packages)) {
  if (path === "") continue;
  if ((info.dev || info.devOptional) && !bundled.has(path)) continue;
  const name = path.slice(path.lastIndexOf("node_modules/") + "node_modules/".length);
  const license = typeof info.license === "string" ? info.license : "";
  if (!license) missing.push(`${name}@${info.version}`);
  rows.push([name, info.version, license || "UNDECLARED"]);
}
rows.sort((a, b) => a[0].localeCompare(b[0]) || a[1].localeCompare(b[1]));

const text = `# Third-party notices

Sheetstamp is MIT-licensed. It ships with the open-source packages below.
Electron bundles Chromium and Node.js; their licenses are in \`LICENSE.electron.txt\` and
\`LICENSES.chromium.html\` next to the application.

Generated by \`scripts/third-party-notices.mjs\` from \`package-lock.json\`. Do not edit by hand.

| Package | Version | License |
| --- | --- | --- |
${rows.map(([name, version, license]) => `| ${name} | ${version} | ${license} |`).join("\n")}
`;

if (missing.length) console.warn(`No license declared: ${missing.join(", ")} (see .work/notes.md)`);
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync("THIRD-PARTY-NOTICES.md", "utf8");
  } catch {}
  if (current !== text) {
    console.error(
      "THIRD-PARTY-NOTICES.md is out of date. Run: node scripts/third-party-notices.mjs",
    );
    process.exit(1);
  }
} else {
  writeFileSync("THIRD-PARTY-NOTICES.md", text);
  console.log(`Wrote ${rows.length} packages`);
}
